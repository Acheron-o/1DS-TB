# Crie duas variáveis, base e expoente, com valores escolhidos pelo usuário,  respectivamente.
#  Calcule o valor de base elevado a expoente e imprima o  resultado

base = int(input("Digite um número inteiro: "))
expoente = int(input("Digite o expoente deste número inteiro: "))
print(f"O número {base} elevado ao expoente {expoente} se resulta em: {base**expoente}")